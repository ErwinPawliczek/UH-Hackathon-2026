// Writes public/editor/site-icons.js from src/ui/siteIcons.ts, so the map
// builder (a static page outside the React bundle) draws the very same site
// icons as the app. Run after changing an icon: node scripts/build-editor-icons.mjs
import { transform } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const here = new URL('.', import.meta.url);
const src = await readFile(new URL('../src/ui/siteIcons.ts', here), 'utf8');
const { code } = await transform(src, { loader: 'ts', format: 'esm' });
const mod = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const out = {};
for (const key of mod.SITE_ICON_ORDER) out[key] = { label: mod.presetLabel(key), markup: mod.iconMarkup(mod.siteIcon(key)) };
await writeFile(
  new URL('../public/editor/site-icons.js', here),
  `// Generated by web/scripts/build-editor-icons.mjs from web/src/ui/siteIcons.ts. Do not edit.\n` +
  `// Each icon is SVG markup on a ${mod.ICON_GRID} x ${mod.ICON_GRID} grid, stroke width ${mod.ICON_STROKE}, round caps and joins.\n` +
  `window.PETROGRID_SITE_ICONS = ${JSON.stringify(out, null, 1)};\n`,
);
console.log('wrote', Object.keys(out).length, 'icons');
